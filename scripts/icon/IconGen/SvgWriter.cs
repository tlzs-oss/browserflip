using System.Text;

namespace BrowserFlip.IconGen;

/// <summary>Emits a clean, dependency-free SVG (no raster, no external references, no fonts).</summary>
internal static class SvgWriter
{
    public static string Write(Artwork art)
    {
        var sb = new StringBuilder();
        sb.Append("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 256 256\" width=\"256\" height=\"256\">\n");
        sb.Append("  <title>BrowserFlip</title>\n");
        sb.Append("  <!-- ").Append(art.Description).Append(". Generated by scripts/icon (Design.cs); edit there, not here. MIT License. -->\n");

        var gradients = art.Shapes
            .SelectMany(s => new[] { s.Fill, s.Stroke })
            .OfType<LinearPaint>()
            .DistinctBy(g => g.Id)
            .ToList();
        if (gradients.Count > 0)
        {
            sb.Append("  <defs>\n");
            foreach (var g in gradients)
            {
                sb.Append("    <linearGradient id=\"").Append(g.Id).Append("\" gradientUnits=\"userSpaceOnUse\" x1=\"").Append(Geo.F(g.X1))
                  .Append("\" y1=\"").Append(Geo.F(g.Y1)).Append("\" x2=\"").Append(Geo.F(g.X2)).Append("\" y2=\"").Append(Geo.F(g.Y2)).Append("\">\n");
                foreach (var st in g.Stops)
                {
                    sb.Append("      <stop offset=\"").Append(Geo.F(st.Offset)).Append("\" stop-color=\"").Append(st.Hex).Append('"');
                    if (st.Opacity < 1)
                    {
                        sb.Append(" stop-opacity=\"").Append(Geo.F(st.Opacity)).Append('"');
                    }

                    sb.Append("/>\n");
                }

                sb.Append("    </linearGradient>\n");
            }

            sb.Append("  </defs>\n");
        }

        foreach (var s in art.Shapes)
        {
            sb.Append("  <!-- ").Append(s.Comment).Append(" -->\n  ");
            switch (s.Kind)
            {
                case ShapeKind.Rect:
                    sb.Append("<rect x=\"").Append(Geo.F(s.X)).Append("\" y=\"").Append(Geo.F(s.Y)).Append("\" width=\"").Append(Geo.F(s.W))
                      .Append("\" height=\"").Append(Geo.F(s.H)).Append("\" rx=\"").Append(Geo.F(s.Rx)).Append('"');
                    break;
                case ShapeKind.Ellipse when s.Rx == s.Ry:
                    sb.Append("<circle cx=\"").Append(Geo.F(s.X)).Append("\" cy=\"").Append(Geo.F(s.Y)).Append("\" r=\"").Append(Geo.F(s.Rx)).Append('"');
                    break;
                case ShapeKind.Ellipse:
                    sb.Append("<ellipse cx=\"").Append(Geo.F(s.X)).Append("\" cy=\"").Append(Geo.F(s.Y)).Append("\" rx=\"").Append(Geo.F(s.Rx))
                      .Append("\" ry=\"").Append(Geo.F(s.Ry)).Append('"');
                    break;
                case ShapeKind.Path:
                    sb.Append("<path d=\"").Append(s.D).Append('"');
                    break;
                default:
                    throw new InvalidOperationException("Unknown shape kind.");
            }

            AppendPaint(sb, "fill", s.Fill);
            if (s.Stroke is not null)
            {
                AppendPaint(sb, "stroke", s.Stroke);
                sb.Append(" stroke-width=\"").Append(Geo.F(s.StrokeWidth)).Append('"');
                sb.Append(" stroke-linecap=\"").Append(s.LineCap).Append("\" stroke-linejoin=\"").Append(s.LineJoin).Append('"');
            }

            sb.Append("/>\n");
        }

        sb.Append("</svg>\n");
        return sb.ToString();
    }

    private static void AppendPaint(StringBuilder sb, string attr, Paint? paint)
    {
        switch (paint)
        {
            case null:
                sb.Append(' ').Append(attr).Append("=\"none\"");
                break;
            case SolidPaint sp:
                sb.Append(' ').Append(attr).Append("=\"").Append(sp.Hex).Append('"');
                if (sp.Opacity < 1)
                {
                    sb.Append(' ').Append(attr).Append("-opacity=\"").Append(Geo.F(sp.Opacity)).Append('"');
                }

                break;
            case LinearPaint lp:
                sb.Append(' ').Append(attr).Append("=\"url(#").Append(lp.Id).Append(")\"");
                break;
            default:
                throw new InvalidOperationException("Unknown paint.");
        }
    }
}
